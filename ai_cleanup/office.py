"""Zip-based documents: DOCX/XLSX/PPTX (OOXML), ODT/ODS/ODP (OpenDocument), EPUB.

Text nodes in every XML part are cleaned, and document properties that identify the
generating tool or author are scrubbed. The zip is rebuilt entry by entry so structure,
ordering and compression (e.g. ODF's uncompressed `mimetype`) are preserved.
"""
from __future__ import annotations

import re
import zipfile
from pathlib import Path

from .report import Options, Report
from .text import clean_markup

OOXML_EXTS = {".docx", ".docm", ".dotx", ".xlsx", ".xlsm", ".pptx", ".pptm", ".potx", ".ppsx"}
ODF_EXTS = {".odt", ".ods", ".odp", ".odg", ".ott"}
EPUB_EXTS = {".epub"}
ZIP_DOC_EXTS = OOXML_EXTS | ODF_EXTS | EPUB_EXTS

_XML_PART = re.compile(r"\.(xml|xhtml|html|htm|opf|ncx|rels|svg)$", re.I)
_AI_WORDS = re.compile(r"(python-docx|python-pptx|openpyxl|docx\.js|officegen|pandoc|chatgpt|openai|"
                       r"copilot|gemini|claude|anthropic|generated by|ai[- ]generated|reportlab|aspose)", re.I)


def _blank(xml: str, tag: str, report: Report, label: str, value: str = "") -> str:
    pat = re.compile(rf"(<{tag}\b[^>]*>)(.*?)(</{tag}>)", re.S)

    def repl(m: re.Match) -> str:
        if m.group(2) != value and (m.group(2).strip() or m.group(2)):
            report.add(label)
            if _AI_WORDS.search(m.group(2)):
                report.note(f"generator/author hint removed: {m.group(2).strip()[:60]!r}")
            return m.group(1) + value + m.group(3)
        return m.group(0)
    return pat.sub(repl, xml)


def _scrub_ooxml_core(xml: str, report: Report) -> str:
    for tag in ("dc:creator", "cp:lastModifiedBy", "dc:description", "cp:keywords",
                "cp:category", "cp:contentStatus", "dc:identifier", "cp:version"):
        xml = _blank(xml, tag, report, "document property")
    xml = _blank(xml, "cp:revision", report, "document property", "1")
    # Word writes whole seconds; generator libraries (docx.js, python-docx...) leave milliseconds
    xml, n = re.subn(r"(<dcterms:(?:created|modified)\b[^>]*>\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d)\.\d+(Z?)",
                     lambda m: m.group(1) + "Z", xml)
    report.add("generator timestamp fingerprint", n)
    return xml


_APP_NAMES = {"word": "Microsoft Office Word", "xl": "Microsoft Excel",
              "ppt": "Microsoft Office PowerPoint"}


_APP_NS = ('xmlns="http://schemas.openxmlformats.org/officeDocument/2006/extended-properties" '
           'xmlns:vt="http://schemas.openxmlformats.org/officeDocument/2006/docPropsVTypes"')


def _word_stats(document_xml: str) -> dict:
    paras = re.findall(r"<w:p[ >].*?</w:p>", document_xml, re.S)
    texts = ["".join(re.findall(r"<w:t(?: [^>]*)?>([^<]*)</w:t>", p)) for p in paras]
    texts = [t for t in texts if t.strip()]
    full = " ".join(texts)
    words = len(full.split())
    chars_sp = sum(len(t) for t in texts)
    chars = chars_sp - sum(t.count(" ") for t in texts)
    lines = max(1, round(chars_sp / 70))
    return {"Pages": max(1, -(-words // 450)), "Words": words, "Characters": chars,
            "Lines": lines, "Paragraphs": len(texts), "CharactersWithSpaces": chars_sp}


def _synth_app_xml(kind: str, stats: dict | None) -> str:
    """Rebuild an app.xml the way the real Office app writes it (generators leave it empty)."""
    app = _APP_NAMES.get(kind, "Microsoft Office Word")
    body = ""
    if kind == "word" and stats:
        body = ("<Template>Normal.dotm</Template><TotalTime>0</TotalTime>"
                f"<Pages>{stats['Pages']}</Pages><Words>{stats['Words']}</Words>"
                f"<Characters>{stats['Characters']}</Characters><Application>{app}</Application>"
                f"<DocSecurity>0</DocSecurity><Lines>{stats['Lines']}</Lines>"
                f"<Paragraphs>{stats['Paragraphs']}</Paragraphs><ScaleCrop>false</ScaleCrop>"
                "<Company></Company><LinksUpToDate>false</LinksUpToDate>"
                f"<CharactersWithSpaces>{stats['CharactersWithSpaces']}</CharactersWithSpaces>"
                "<SharedDoc>false</SharedDoc><HyperlinksChanged>false</HyperlinksChanged>")
    else:
        body = (f"<Application>{app}</Application><DocSecurity>0</DocSecurity>"
                "<ScaleCrop>false</ScaleCrop><Company></Company><LinksUpToDate>false</LinksUpToDate>"
                "<SharedDoc>false</SharedDoc><HyperlinksChanged>false</HyperlinksChanged>")
    return ('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>\r\n'
            f"<Properties {_APP_NS}>{body}<AppVersion>16.0000</AppVersion></Properties>")


def _scrub_ooxml_app(xml: str, kind: str, report: Report, stats: dict | None = None) -> str:
    if "<Application>" not in xml:
        report.add("generator fingerprint (empty app.xml)")
        return _synth_app_xml(kind, stats)
    app = _APP_NAMES.get(kind, "")
    xml = _blank(xml, "Application", report, "generator tag", app)
    for tag in ("Company", "Manager", "HyperlinkBase"):
        xml = _blank(xml, tag, report, "document property")
    xml = re.sub(r"<AppVersion>[^<]*</AppVersion>", "<AppVersion>16.0000</AppVersion>", xml)
    return xml


def _scrub_odf_meta(xml: str, report: Report) -> str:
    for tag in ("meta:generator", "dc:creator", "meta:initial-creator", "dc:description",
                "meta:keyword", "meta:printed-by"):
        xml = _blank(xml, tag, report, "document property" if tag != "meta:generator" else "generator tag")
    xml, n = re.subn(r"<meta:user-defined\b[^>]*?(?:/>|>.*?</meta:user-defined>)", "", xml, flags=re.S)
    report.add("custom property", n)
    xml = re.sub(r"(<meta:editing-cycles>)[^<]*(</meta:editing-cycles>)", r"\g<1>1\2", xml)
    return xml


def _scrub_epub_opf(xml: str, report: Report) -> str:
    xml, n = re.subn(r'\s*<meta\b[^>]*name="generator"[^>]*/>', "", xml)
    report.add("generator tag", n)
    xml, n = re.subn(r"\s*<dc:contributor\b[^>]*>[^<]*</dc:contributor>", "", xml)
    report.add("document property", n)
    return xml


def clean_zip_document(src: Path, dst: Path, opts: Options, report: Report) -> Path:
    ext = src.suffix.lower()
    with zipfile.ZipFile(src) as zin:
        names = zin.namelist()
        drop: set[str] = set()
        if opts.metadata and ext in OOXML_EXTS:
            # custom.xml holds custom properties: AI/sensitivity labels, tool tags, IDs
            drop = {n for n in names if n.lower() == "docprops/custom.xml"}
            if drop:
                report.add("custom property part")
        kind = next((n.split("/")[0] for n in names if n.split("/")[0] in _APP_NAMES), "")
        stats = None
        if kind == "word" and "word/document.xml" in names:
            stats = _word_stats(zin.read("word/document.xml").decode("utf-8", "replace"))
        drop_targets: list[str] = []
        if opts.metadata and ext in OOXML_EXTS:
            # generators emit empty comment parts; Word only creates them when comments exist
            for n in names:
                if re.fullmatch(r"word/comments(?:Extended|Ids|Extensible)?\.xml", n):
                    if b"<w:comment " not in zin.read(n) and b"<w15:commentEx " not in zin.read(n) \
                            and b"<w16cid:commentId " not in zin.read(n):
                        drop.add(n)
                        drop.add(n.replace("word/", "word/_rels/") + ".rels")
                        drop_targets.append(n.split("/", 1)[1])
            if drop_targets:
                report.add("empty generator part", len(drop_targets))

        with zipfile.ZipFile(dst, "w") as zout:
            for info in zin.infolist():
                if info.filename in drop:
                    continue
                data = zin.read(info.filename)
                lname = info.filename.lower()
                if _XML_PART.search(lname):
                    try:
                        xml = data.decode("utf-8")
                    except UnicodeDecodeError:
                        zout.writestr(info, data)
                        continue
                    if opts.metadata:
                        if lname == "docprops/core.xml":
                            xml = _scrub_ooxml_core(xml, report)
                        elif lname == "docprops/app.xml":
                            xml = _scrub_ooxml_app(xml, kind, report, stats)
                        elif lname == "meta.xml":
                            xml = _scrub_odf_meta(xml, report)
                        elif lname.endswith(".opf"):
                            xml = _scrub_epub_opf(xml, report)
                        if drop and lname in ("[content_types].xml", "_rels/.rels"):
                            xml = re.sub(r'<(?:Override|Relationship)\b[^>]*docProps/custom\.xml[^>]*/>', "", xml)
                        for t in drop_targets:
                            if lname in ("[content_types].xml", "word/_rels/document.xml.rels"):
                                xml = re.sub(r'<(?:Override|Relationship)\b[^>]*"/?(?:word/)?'
                                             + re.escape(t) + r'"[^>]*/>', "", xml)
                    if not lname.endswith(".rels"):
                        xml, _ = clean_markup(xml, opts, report, html=lname.endswith((".xhtml", ".html", ".htm")))
                    data = xml.encode("utf-8")
                zout.writestr(info, data)
    return dst
